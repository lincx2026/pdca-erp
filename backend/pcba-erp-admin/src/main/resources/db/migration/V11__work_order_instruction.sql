CREATE TABLE pmm_work_instruction (
    work_order_id bigint PRIMARY KEY REFERENCES pmm_work_order(work_order_id) ON DELETE CASCADE,
    content jsonb NOT NULL,
    version integer NOT NULL DEFAULT 1,
    updated_by varchar(64),
    updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE pmm_work_instruction_attachment (
    attachment_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    work_order_id bigint NOT NULL REFERENCES pmm_work_order(work_order_id) ON DELETE CASCADE,
    file_name varchar(255) NOT NULL,
    object_key varchar(500) NOT NULL UNIQUE,
    content_type varchar(100) NOT NULL,
    file_size bigint NOT NULL,
    kind varchar(16) NOT NULL CHECK (kind IN ('IMAGE', 'FIRMWARE')),
    created_by varchar(64),
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX pmm_work_instruction_attachment_order_idx ON pmm_work_instruction_attachment(work_order_id);
